// Builds public/mission-engine.js: the SAME strategy/lab code as the bot (lab.js + friends), wrapped for the browser.
// node build-mission.js          → write it      ·   node build-mission.js --check → exit 1 if it is out of date
'use strict';
const fs = require('fs'), path = require('path');
const MODS = ['volumeProfile', 'vpStrategies', 'runner', 'labStrategies', 'lab', 'labTrack'];
function build(){
  let b = '/* GENERATED by build-mission.js from the bot modules — do not edit by hand. Paper only: no keys, no wallet, no transactions. */\n'
    + '(function(){var D={},C={};function R(n){n=String(n).replace(/^\\.\\//,"").replace(/\\.js$/,"");if(C[n])return C[n].exports;if(!D[n])throw new Error("module "+n);var m={exports:{}};C[n]=m;D[n](m,m.exports,R);return m.exports;}\n'
    + 'var process={env:{}};\n';
  for (const n of MODS) b += 'D["' + n + '"]=function(module,exports,require){\n' + fs.readFileSync(path.join(__dirname, n + '.js'), 'utf8') + '\n};\n';
  b += 'window.LABMOD={lab:R("lab"),track:R("labTrack"),vp:R("volumeProfile")};})();\n';
  return b;
}
const out = path.join(__dirname, 'public', 'mission-engine.js'), want = build();
if (process.argv.includes('--check')){
  const have = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (have !== want){ console.error('public/mission-engine.js loopt achter — draai: node build-mission.js'); process.exit(1); }
  console.log('mission-engine.js gelijk aan de bot-code ✓');
} else { fs.writeFileSync(out, want); console.log('geschreven', out, want.length, 'tekens'); }
